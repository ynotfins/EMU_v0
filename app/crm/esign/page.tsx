"use client"

import { useState, useEffect } from "react"
import { collection, query, where, orderBy, onSnapshot, addDoc, doc, getDoc } from "firebase/firestore"
import { db, auth } from "@/lib/firebase"
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "@/components/ui/card"
import { Button } from "@/components/ui/button"
import { Badge } from "@/components/ui/badge"
import { Input } from "@/components/ui/input"
import { ProtectedRoute } from "@/components/protected-route"
import { useToast } from "@/hooks/use-toast"
import { ESignature, type SignatureData } from "@/components/e-signature"
import {
  FileSignature, Clock, CheckCircle, AlertCircle, X,
  Download, Eye, Shield, Search, Calendar, User
} from "lucide-react"
import { spacing, borderRadius, cardStyles, colors } from "@/lib/design-tokens"
import type { ESignature as ESignatureType, Document } from "@/types/domain"

export default function CRMESignPage() {
  const { toast } = useToast()
  const [signatures, setSignatures] = useState<ESignatureType[]>([])
  const [filteredSignatures, setFilteredSignatures] = useState<ESignatureType[]>([])
  const [loading, setLoading] = useState(true)
  const [searchTerm, setSearchTerm] = useState("")
  const [signingDocument, setSigningDocument] = useState<Document | null>(null)

  useEffect(() => {
    if (!auth.currentUser) return

    console.log("[CRM E-Sign] Loading signatures...")

    // Query signatures where user is involved
    const q = query(
      collection(db, "esignatures"),
      orderBy("createdAt", "desc")
    )

    const unsubscribe = onSnapshot(
      q,
      (snapshot) => {
        const signaturesList: ESignatureType[] = []
        snapshot.forEach((doc) => {
          signaturesList.push({
            id: doc.id,
            ...doc.data()
          } as ESignatureType)
        })

        console.log(`[CRM E-Sign] Loaded ${signaturesList.length} signatures`)
        setSignatures(signaturesList)
        setFilteredSignatures(signaturesList)
        setLoading(false)
      },
      (error) => {
        console.error("[CRM E-Sign] Error loading signatures:", error)
        setLoading(false)
      }
    )

    return () => unsubscribe()
  }, [])

  // Filter signatures
  useEffect(() => {
    let filtered = signatures

    if (searchTerm) {
      filtered = filtered.filter((sig) =>
        sig.signer.name.toLowerCase().includes(searchTerm.toLowerCase()) ||
        sig.signer.email.toLowerCase().includes(searchTerm.toLowerCase()) ||
        sig.documentId.toLowerCase().includes(searchTerm.toLowerCase())
      )
    }

    setFilteredSignatures(filtered)
  }, [signatures, searchTerm])

  // Stats
  const stats = {
    total: signatures.length,
    pending: signatures.filter(s => s.status === "pending").length,
    signed: signatures.filter(s => s.status === "signed").length,
    expired: signatures.filter(s => s.status === "expired").length
  }

  // Handle document signing
  const handleSignDocument = async (signatureData: SignatureData) => {
    if (!signingDocument) return

    try {
      // Create e-signature record
      const newSignature: Omit<ESignatureType, "id"> = {
        documentId: signingDocument.id,
        createdAt: new Date().toISOString(),
        completedAt: new Date().toISOString(),
        signer: {
          name: signatureData.signerName,
          email: signatureData.signerEmail,
          phone: signatureData.signerPhone,
          title: signatureData.signerTitle
        },
        signature: {
          image: signatureData.signatureImage,
          timestamp: signatureData.timestamp,
          ipAddress: signatureData.ipAddress,
          deviceFingerprint: signatureData.deviceFingerprint,
          timezone: signatureData.timezone,
          userAgent: signatureData.userAgent
        },
        compliance: {
          documentHash: signatureData.documentHash,
          consentGiven: signatureData.consentGiven,
          consentText: signatureData.consentText,
          certificateUrl: "" // Would be generated by signing service
        },
        status: "signed"
      }

      await addDoc(collection(db, "esignatures"), newSignature)

      toast({
        title: "Document Signed",
        description: "E-signature has been recorded successfully",
      })

      setSigningDocument(null)
    } catch (error) {
      console.error("Error saving signature:", error)
      toast({
        title: "Error",
        description: "Failed to save signature",
        variant: "destructive"
      })
    }
  }

  // Generate certificate
  const generateCertificate = (signature: ESignatureType) => {
    // In production, this would generate a PDF certificate
    const cert = `
CERTIFICATE OF ELECTRONIC SIGNATURE

Document ID: ${signature.documentId}
Signed by: ${signature.signer.name}
Email: ${signature.signer.email}
Date: ${new Date(signature.signature.timestamp).toLocaleString()}
IP Address: ${signature.signature.ipAddress}
Device ID: ${signature.signature.deviceFingerprint}

This document was signed electronically in accordance with the ESIGN Act.
    `.trim()

    const blob = new Blob([cert], { type: 'text/plain' })
    const url = URL.createObjectURL(blob)
    const a = document.createElement('a')
    a.href = url
    a.download = `certificate_${signature.id}.txt`
    a.click()
    URL.revokeObjectURL(url)
  }

  if (loading) {
    return (
      <ProtectedRoute>
        <div className="flex items-center justify-center min-h-screen">
          <p>Loading e-signatures...</p>
        </div>
      </ProtectedRoute>
    )
  }

  // Show signing interface if document selected
  if (signingDocument) {
    return (
      <ProtectedRoute>
        <div style={{ padding: spacing['2xl'] }}>
          <ESignature
            documentId={signingDocument.id}
            documentTitle={signingDocument.title}
            onSign={handleSignDocument}
            onCancel={() => setSigningDocument(null)}
          />
        </div>
      </ProtectedRoute>
    )
  }

  return (
    <ProtectedRoute>
      <div style={{ padding: spacing['2xl'], maxWidth: "1400px", margin: "0 auto" }}>
        {/* Header */}
        <div className="mb-8">
          <h1 className="text-4xl font-bold mb-2">E-Signatures</h1>
          <p className="text-gray-600">
            Manage electronic signatures with legal compliance
          </p>
        </div>

        {/* Stats Cards */}
        <div className="grid grid-cols-1 md:grid-cols-4 gap-6 mb-8">
          <Card style={{ ...cardStyles.base, padding: spacing.lg }}>
            <CardContent className="p-0">
              <div className="flex items-center justify-between">
                <div>
                  <p className="text-sm text-gray-500">Total Signatures</p>
                  <p className="text-3xl font-bold">{stats.total}</p>
                </div>
                <FileSignature className="h-8 w-8 text-gray-400" />
              </div>
            </CardContent>
          </Card>

          <Card style={{ ...cardStyles.base, padding: spacing.lg }}>
            <CardContent className="p-0">
              <div className="flex items-center justify-between">
                <div>
                  <p className="text-sm text-gray-500">Pending</p>
                  <p className="text-3xl font-bold">{stats.pending}</p>
                </div>
                <Clock className="h-8 w-8 text-orange-500" />
              </div>
            </CardContent>
          </Card>

          <Card style={{ ...cardStyles.base, padding: spacing.lg }}>
            <CardContent className="p-0">
              <div className="flex items-center justify-between">
                <div>
                  <p className="text-sm text-gray-500">Signed</p>
                  <p className="text-3xl font-bold">{stats.signed}</p>
                </div>
                <CheckCircle className="h-8 w-8 text-green-500" />
              </div>
            </CardContent>
          </Card>

          <Card style={{ ...cardStyles.base, padding: spacing.lg }}>
            <CardContent className="p-0">
              <div className="flex items-center justify-between">
                <div>
                  <p className="text-sm text-gray-500">Expired</p>
                  <p className="text-3xl font-bold">{stats.expired}</p>
                </div>
                <AlertCircle className="h-8 w-8 text-red-500" />
              </div>
            </CardContent>
          </Card>
        </div>

        {/* Search */}
        <Card style={{ ...cardStyles.base, marginBottom: spacing.lg }}>
          <CardContent style={{ padding: spacing.lg }}>
            <div className="relative">
              <Search className="absolute left-3 top-1/2 transform -translate-y-1/2 h-4 w-4 text-gray-400" />
              <Input
                placeholder="Search by signer name, email, or document ID..."
                value={searchTerm}
                onChange={(e) => setSearchTerm(e.target.value)}
                className="pl-10"
                style={{ borderRadius: borderRadius.DEFAULT }}
              />
            </div>
          </CardContent>
        </Card>

        {/* Demo Sign Button */}
        <Card style={{ ...cardStyles.base, marginBottom: spacing.lg }}>
          <CardHeader>
            <CardTitle>Try E-Signature</CardTitle>
            <CardDescription>
              Test the e-signature system with a demo document
            </CardDescription>
          </CardHeader>
          <CardContent>
            <Button
              onClick={() => setSigningDocument({
                id: "demo-doc",
                title: "Sample Service Agreement",
                type: "contract",
                status: "pending_review",
                createdAt: new Date().toISOString(),
                updatedAt: new Date().toISOString(),
                file: {
                  url: "",
                  name: "sample-agreement.pdf",
                  size: 1024000,
                  mimeType: "application/pdf",
                  storageRef: ""
                },
                metadata: {
                  version: 1,
                  tags: ["demo", "test"]
                },
                owner: auth.currentUser?.uid || "",
                sharedWith: [],
                permissions: {},
                history: []
              } as Document)}
            >
              <FileSignature className="h-4 w-4 mr-2" />
              Sign Demo Document
            </Button>
          </CardContent>
        </Card>

        {/* Signatures List */}
        <div className="space-y-4">
          {filteredSignatures.map((signature) => {
            const statusConfig = {
              pending: { color: colors.warning.DEFAULT, bg: colors.warning.light, label: "Pending" },
              signed: { color: colors.success.DEFAULT, bg: colors.success.light, label: "Signed" },
              declined: { color: colors.danger.DEFAULT, bg: colors.danger.light, label: "Declined" },
              expired: { color: colors.gray[500], bg: colors.gray[100], label: "Expired" }
            }[signature.status]

            return (
              <Card 
                key={signature.id}
                style={{ 
                  ...cardStyles.base,
                  transition: "all 0.2s"
                }}
                className="hover:shadow-md"
              >
                <CardContent style={{ padding: spacing.lg }}>
                  <div className="flex items-start gap-4">
                    {/* Status Icon */}
                    <div 
                      className="p-3 rounded-lg"
                      style={{ 
                        backgroundColor: statusConfig.bg,
                        color: statusConfig.color
                      }}
                    >
                      {signature.status === "signed" ? (
                        <CheckCircle className="h-6 w-6" />
                      ) : signature.status === "pending" ? (
                        <Clock className="h-6 w-6" />
                      ) : signature.status === "declined" ? (
                        <X className="h-6 w-6" />
                      ) : (
                        <AlertCircle className="h-6 w-6" />
                      )}
                    </div>

                    {/* Signature Info */}
                    <div className="flex-1">
                      <div className="flex items-start justify-between mb-3">
                        <div>
                          <h3 className="font-semibold text-lg">{signature.signer.name}</h3>
                          <p className="text-sm text-gray-600">{signature.signer.email}</p>
                          {signature.signer.title && (
                            <p className="text-sm text-gray-500">{signature.signer.title}</p>
                          )}
                        </div>
                        <Badge
                          style={{
                            backgroundColor: statusConfig.bg,
                            color: statusConfig.color,
                            border: "none"
                          }}
                        >
                          {statusConfig.label}
                        </Badge>
                      </div>

                      {/* Metadata */}
                      <div className="grid grid-cols-2 md:grid-cols-4 gap-4 text-sm">
                        <div>
                          <p className="text-gray-500">Document</p>
                          <p className="font-medium">#{signature.documentId.slice(0, 8)}</p>
                        </div>
                        <div>
                          <p className="text-gray-500">Signed Date</p>
                          <p className="font-medium">
                            {signature.completedAt 
                              ? new Date(signature.completedAt).toLocaleDateString()
                              : "Not signed"
                            }
                          </p>
                        </div>
                        <div>
                          <p className="text-gray-500">IP Address</p>
                          <p className="font-medium">{signature.signature?.ipAddress || "N/A"}</p>
                        </div>
                        <div>
                          <p className="text-gray-500">Security</p>
                          <p className="font-medium flex items-center gap-1">
                            <Shield className="h-3 w-3" />
                            Verified
                          </p>
                        </div>
                      </div>

                      {/* Actions */}
                      {signature.status === "signed" && (
                        <div className="flex gap-2 mt-4">
                          <Button
                            variant="outline"
                            size="sm"
                            onClick={() => {
                              // View signature image
                              if (signature.signature?.image) {
                                const win = window.open()
                                win?.document.write(`<img src="${signature.signature.image}" />`)
                              }
                            }}
                          >
                            <Eye className="h-4 w-4 mr-1" />
                            View Signature
                          </Button>
                          <Button
                            variant="outline"
                            size="sm"
                            onClick={() => generateCertificate(signature)}
                          >
                            <Download className="h-4 w-4 mr-1" />
                            Certificate
                          </Button>
                        </div>
                      )}
                    </div>
                  </div>
                </CardContent>
              </Card>
            )
          })}
        </div>

        {/* Empty State */}
        {filteredSignatures.length === 0 && (
          <Card style={{ ...cardStyles.base, textAlign: "center", padding: spacing['3xl'] }}>
            <CardContent className="p-0">
              <FileSignature className="h-16 w-16 text-gray-300 mx-auto mb-4" />
              <h3 className="text-lg font-medium mb-2">No signatures found</h3>
              <p className="text-gray-500 mb-6">
                {searchTerm
                  ? "Try adjusting your search"
                  : "Send your first document for e-signature"}
              </p>
            </CardContent>
          </Card>
        )}
      </div>
    </ProtectedRoute>
  )
}
